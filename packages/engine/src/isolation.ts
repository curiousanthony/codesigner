import { execFileSync } from 'node:child_process';
import { appendFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, isAbsolute, join } from 'node:path';

/** URL of the component canvas page served by the user's own dev server. */
export const ISOLATION_PATH = '/__codesigner';
export const ISOLATION_DIR = 'src/routes/__codesigner';
const ISOLATION_FILE = `${ISOLATION_DIR}/+page@.svelte`;

/**
 * The component canvas: renders one component in every variant × state cell
 * described by `?spec=` (JSON). `+page@.svelte` resets to the root layout so
 * the app's styles load without its shell. Inline styles only: the file is
 * git-ignored, so Tailwind doesn't scan it.
 */
const PAGE = `<!-- Generated by Codesigner for its component canvas. Git-ignored; safe to delete. -->
<script lang="ts">
	import { afterNavigate } from '$app/navigation';
	import { createRawSnippet, onMount } from 'svelte';

	type Cell = { label: string; props: Record<string, unknown>; context: Record<string, string>; state?: string };
	type Spec = { file: string; name: string; text: string | null; sections: { title: string; cells: Cell[] }[] };

	const modules = import.meta.glob('/src/**/*.svelte');
	let spec = $state<Spec | null>(null);
	let Component = $state<any>(null);
	let error = $state('');

	async function load() {
		error = '';
		try {
			const raw = new URLSearchParams(location.search).get('spec');
			spec = raw ? JSON.parse(raw) : null;
			if (!spec) return;
			const loader = modules['/' + spec.file];
			if (!loader) throw new Error('Component not found: ' + spec.file);
			Component = ((await loader()) as { default: unknown }).default;
		} catch (e) {
			error = String(e);
		}
	}
	// onMount also covers hot reloads, which re-create this page without a navigation.
	onMount(() => void load());
	afterNavigate(() => void load());

	const escape = (t: string) => t.replace(/[&<>"]/g, (c) => '&#' + c.charCodeAt(0) + ';');
	const label = (t: string) => createRawSnippet(() => ({ render: () => '<span>' + escape(t) + '</span>' }));
</script>

<div style="min-height:100vh; padding:48px; box-sizing:border-box; font-family:Inter,system-ui,sans-serif;">
	{#if error}
		<p style="color:#e5484d; font-size:13px;">{error}</p>
	{:else if spec && Component}
		<div style="display:inline-flex; flex-direction:column; gap:36px; padding:32px; border:1px dashed #8855ff; border-radius:12px;">
			{#each spec.sections as section (section.title)}
				<section style="display:flex; flex-direction:column; gap:14px;">
					<h2 style="margin:0; font-size:11px; font-weight:600; letter-spacing:.04em; text-transform:uppercase; color:#8855ff;">{section.title}</h2>
					<div style="display:flex; flex-wrap:wrap; align-items:flex-start; gap:28px 40px;">
						{#each section.cells as cell (cell.label)}
							<div style="display:flex; flex-direction:column; gap:8px; align-items:flex-start;">
								<span style="font-size:11px; color:#8855ff;">{cell.label}</span>
								<div
									data-codesigner-context={JSON.stringify(cell.context)}
									data-codesigner-label={cell.label}
									data-codesigner-state={cell.state ?? ''}
									style="display:flex;"
								>
									<svelte:boundary>
										{#if spec.text !== null}
											<Component {...cell.props} children={label(spec.text)} />
										{:else}
											<Component {...cell.props} />
										{/if}
										{#snippet failed(e)}
											<span style="color:#e5484d; font-size:12px;">{String(e)}</span>
										{/snippet}
									</svelte:boundary>
								</div>
							</div>
						{/each}
					</div>
				</section>
			{/each}
		</div>
	{/if}
</div>
`;

function gitCommonDir(root: string): string | null {
	try {
		const out = execFileSync('git', ['rev-parse', '--git-common-dir'], { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
		return isAbsolute(out) ? out : join(root, out);
	} catch {
		return null;
	}
}

/**
 * Writes the component canvas route into the working copy and makes git ignore
 * it (in .git/info/exclude, never in the project's .gitignore), so it is never
 * committed, checkpointed or shipped.
 */
export function ensureIsolationRoute(root: string): string {
	const file = join(root, ISOLATION_FILE);
	if (!existsSync(file) || readFileSync(file, 'utf8') !== PAGE) {
		mkdirSync(dirname(file), { recursive: true });
		writeFileSync(file, PAGE);
	}
	const common = gitCommonDir(root);
	if (common) {
		const exclude = join(common, 'info', 'exclude');
		const line = `/${ISOLATION_DIR}/`;
		const current = existsSync(exclude) ? readFileSync(exclude, 'utf8') : '';
		if (!current.split('\n').includes(line)) {
			mkdirSync(dirname(exclude), { recursive: true });
			appendFileSync(exclude, `${current && !current.endsWith('\n') ? '\n' : ''}# Codesigner component canvas\n${line}\n`);
		}
	}
	return ISOLATION_PATH;
}
